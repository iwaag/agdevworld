// `wfe setup <area>`: creates or refreshes an authoring area for a person and
// their IDE agent. It writes the generated, machine-specific files (guide,
// launcher, start notes, agent settings) and an empty registry when there is
// none. It never creates a project and keeps everything else in the area.
import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readTextOrNull } from '../server/files.ts'
import { loadRegistry, RegistryError } from '../server/registry.ts'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = resolve(here, '..')
const templates = join(pkg, 'templates')
// First line of every generated Markdown file. A file without it was edited
// by hand and is kept.
const STAMP = '<!-- Generated by `wfe setup` from workflow_editor/templates/. Delete this line to keep local edits. -->'

export interface SetupResult {
  area: string
  launcher: string
  url: string
  serve: string
  files: { path: string; status: 'written' | 'unchanged' | 'kept' | 'created' | 'error'; note?: string }[]
  prompt: string
  runPrompt: string
  summary: string
}

export const FIRST_PROMPT = 'Create a project in this authoring area for <purpose>. Clarify its intent and goals, establish the repositories it needs, and create one workflow. Make the result available in the editor for me to review and adjust.'
export const RUN_PROMPT = 'Execute workflow <workflow id> of project <project id> with the braindump below. Save my words as the run\'s braindump with me as the author, record the run with wfe as you work, and write your plan and reports in the run folder. Ask me here or as a run question when you need me.'

const fill = (text: string, vars: Record<string, string>) => text.replace(/\{\{([A-Z_]+)\}\}/g, (_, k: string) => vars[k] ?? `{{${k}}}`)
const sh = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`

const LOCAL_PROJECTS = 'Projects live beneath this directory, each in its own Git repository\n  (`pj-<id>/`). This directory is not a project. `sources/` holds the local\n  repositories that projects use as submodules.'

// installed (workflow_editor p13): the operating area's authoring entry,
// written to <area>/authoring/ by the release script. It uses the area's
// installed launcher, service and docs (through service/current), creates
// nothing else, and sits beside the project workspaces rather than above
// them: an AGENTS.md or CLAUDE.md in an ancestor of a run copy would be read
// by every executing agent's harness.
export async function setupArea(area: string, opts: { port: number; installed?: { url: string } }): Promise<SetupResult> {
  if (opts.installed) return setupInstalled(area, opts.installed.url)
  const files: SetupResult['files'] = []
  const launcher = join(area, 'wfe')
  const registry = join(area, 'registry.json')
  const url = `http://127.0.0.1:${opts.port}/`
  const serve = `${launcher} serve`
  await mkdir(join(area, 'sources'), { recursive: true })

  // The registry is the person's state: created when missing, never rewritten.
  try {
    const reg = await loadRegistry(registry)
    if (!reg.exists) {
      await writeFile(registry, `${JSON.stringify({ approver: '', workspaces: [] }, null, 2)}\n`)
      files.push({ path: registry, status: 'created', note: 'empty' })
    } else files.push({ path: registry, status: 'kept', note: `${reg.workspaces.length} workspace(s)` })
  } catch (e) {
    if (!(e instanceof RegistryError)) throw e
    files.push({ path: registry, status: 'error', note: `${e.message}` })
  }

  // Generated files: rewritten from the templates unless edited by hand.
  const vars = { AREA: area, WFE: launcher, URL: url, SERVE: serve, CONTRACT: join(pkg, 'docs', 'contract.md'), RUN_CONTRACT: join(pkg, 'docs', 'runs.md'), PROJECTS: LOCAL_PROJECTS }
  const generated = async (path: string, body: string, opts2: { stamp?: boolean; mode?: number } = {}) => {
    const text = opts2.stamp === false ? body : `${STAMP}\n${body}`
    const current = await readTextOrNull(path)
    if (current === text) { files.push({ path, status: 'unchanged' }); return }
    if (current !== null && opts2.stamp !== false && !current.startsWith(STAMP)) { files.push({ path, status: 'kept', note: 'edited by hand (no generated stamp)' }); return }
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, text)
    if (opts2.mode) await chmod(path, opts2.mode)
    files.push({ path, status: 'written' })
  }
  await generated(join(area, 'AGENTS.md'), fill(await readFile(join(templates, 'AGENTS.md'), 'utf8'), vars))
  await generated(join(area, 'CLAUDE.md'), '@AGENTS.md\n')
  await generated(join(area, 'START.md'), fill(await readFile(join(templates, 'START.md'), 'utf8'), vars))
  await generated(launcher, [
    '#!/bin/sh',
    '# Generated by `wfe setup`: the workflow editor CLI with this area\'s registry and port.',
    `NODE=$(command -v node || echo ${sh(process.execPath)})`,
    `WFE_REGISTRY=${sh(registry)} WFE_AREA=${sh(area)} WFE_PORT=${sh(String(opts.port))} exec "$NODE" ${sh(join(pkg, 'cli', 'wfe.ts'))} "$@"`,
    '',
  ].join('\n'), { stamp: false, mode: 0o755 })

  // Claude Code permissions (CLI and VS Code extension) for the area's own
  // tools and edits beneath it; Edit rules cover writes. Kept once it exists.
  const settings = join(area, '.claude', 'settings.json')
  if (await readTextOrNull(settings) === null) {
    await mkdir(dirname(settings), { recursive: true })
    await writeFile(settings, `${JSON.stringify({ permissions: { allow: [`Bash(${launcher} *)`, 'Bash(./wfe *)', 'Bash(git *)', 'Edit(./**)'] } }, null, 2)}\n`)
    files.push({ path: settings, status: 'created' })
  } else files.push({ path: settings, status: 'kept' })

  const summary = [
    `Authoring area: ${area}`,
    ...files.map(f => `  ${f.status.padEnd(9)} ${f.path}${f.note ? ` (${f.note})` : ''}`),
    '',
    `Tool:     ${launcher} help`,
    `Service:  ${serve}`,
    `Browser:  ${url}`,
    `IDE:      open ${area} in VS Code and start the agent there (it reads AGENTS.md; Claude Code via CLAUDE.md)`,
    'Prompt (authoring):',
    `  ${FIRST_PROMPT}`,
    'Prompt (executing a workflow; add the braindump after it):',
    `  ${RUN_PROMPT}`,
    `Runs:     ${url}#/ws/<project id> → Runs; folders devdocs/runs/<workflow id>/<run id>/; ${launcher} run help`,
    '',
    'No project or run was created. START.md in the area repeats these steps.',
  ].join('\n')
  return { area, launcher, url, serve, files, prompt: FIRST_PROMPT, runPrompt: RUN_PROMPT, summary }
}

async function setupInstalled(area: string, url: string): Promise<SetupResult> {
  const files: SetupResult['files'] = []
  const dir = join(area, 'authoring')
  const launcher = join(area, 'bin', 'wfe')
  const docs = join(area, 'service', 'current', 'docs')
  const vars = { AREA: dir, WFE: launcher, URL: url, SERVE: 'the area\'s service (launchd com.agdev.wfe-service); nothing to start', CONTRACT: join(docs, 'contract.md'), RUN_CONTRACT: join(docs, 'runs.md'),
    PROJECTS: `Projects are the workspaces of this operating area, \`${area}/pj-<id>/\` (\`wfe list\`), each in its own Git repository. This directory is only the entry; it is not a project.` }
  const generated = async (path: string, body: string) => {
    const text = `${STAMP}\n${body}`
    const current = await readTextOrNull(path)
    if (current === text) { files.push({ path, status: 'unchanged' }); return }
    if (current !== null && !current.startsWith(STAMP)) { files.push({ path, status: 'kept', note: 'edited by hand (no generated stamp)' }); return }
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, text)
    files.push({ path, status: 'written' })
  }
  await generated(join(dir, 'AGENTS.md'), fill(await readFile(join(templates, 'AGENTS.md'), 'utf8'), vars))
  await generated(join(dir, 'CLAUDE.md'), '@AGENTS.md\n')
  const summary = [`Authoring entry: ${dir}`, ...files.map(f => `  ${f.status.padEnd(9)} ${f.path}${f.note ? ` (${f.note})` : ''}`), `Tool: ${launcher} help`, `Browser: ${url}`].join('\n')
  return { area: dir, launcher, url, serve: vars.SERVE, files, prompt: FIRST_PROMPT, runPrompt: RUN_PROMPT, summary }
}
