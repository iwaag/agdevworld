// Seeds the local fixture: bare source repositories, a project with devdocs,
// study, wedo and other submodules, and two workspaces cloned from it.
//
//   node scripts/seed.ts [--root <dir>] [--reset]
//
// The default root is .local/fixture in this package (ignored by Git). The
// generated repositories, workspaces and registry stay there. Commits use a
// fixed identity and dates so that a reseed produces the same hashes.
import { cp, mkdir, readdir, rm, stat, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gitOk, LOCAL_TRANSPORT } from '../server/git.ts'

const here = dirname(fileURLToPath(import.meta.url))
const pkg = resolve(here, '..')
const examples = join(pkg, 'examples', 'project')
const MARKER = '.workflow-editor-fixture'

const args = process.argv.slice(2)
const flag = (name: string) => args.includes(name)
const option = (name: string) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined }
export const DEFAULT_ROOT = resolve(pkg, '.local', 'fixture')

const FIXED_DATE = '2026-10-01T09:00:00+09:00'
const env = {
  GIT_AUTHOR_NAME: 'Fixture Author', GIT_AUTHOR_EMAIL: 'fixture@example.invalid', GIT_AUTHOR_DATE: FIXED_DATE,
  GIT_COMMITTER_NAME: 'Fixture Author', GIT_COMMITTER_EMAIL: 'fixture@example.invalid', GIT_COMMITTER_DATE: FIXED_DATE,
}
const config = { ...LOCAL_TRANSPORT, 'commit.gpgsign': 'false', 'init.defaultBranch': 'main', 'core.hooksPath': '/dev/null' }
const run = (cwd: string, a: string[]) => gitOk(cwd, a, { env, config })

// Source repositories: name -> files. Submodule paths are chosen in the root.
const SOURCES: Record<string, Record<string, string>> = {
  'devdocs': { 'README.md': '# devdocs\n\nRequests, plans, reports and workflow definitions.\n' },
  'study-agentic-patterns': { 'README.md': '# study-agentic-patterns\n\nNotes on agent workflow patterns.\n' },
  'study-tools': { 'README.md': '# study-tools\n\nNotes on tools and repository conventions.\n' },
  'study-evals': { 'README.md': '# study-evals\n\nEvaluation notes. Not a submodule until added through the editor.\n' },
  'wedo-runtime': { 'README.md': '# wedo-runtime\n\nRuntime configuration and what was learned building it.\n' },
  'wedo-pipeline': { 'README.md': '# wedo-pipeline\n\nDelivery pipeline and its lessons.\n' },
  'shared-assets': { 'README.md': '# shared-assets\n\nShared assets; neither study nor wedo.\n' },
}
// [source, project-relative path]
const SUBMODULES: [string, string][] = [
  ['devdocs', 'devdocs'],
  ['study-agentic-patterns', 'study/agentic-patterns'],
  ['study-tools', 'study/tools'],
  ['wedo-runtime', 'wedo/runtime'],
  ['wedo-pipeline', 'wedo/pipeline'],
  ['shared-assets', 'assets/shared'],
]

async function exists(p: string) { try { await stat(p); return true } catch { return false } }

async function writeFiles(dir: string, files: Record<string, string>) {
  for (const [name, text] of Object.entries(files)) {
    await mkdir(dirname(join(dir, name)), { recursive: true })
    await writeFile(join(dir, name), text)
  }
}

async function source(root: string, name: string, files: Record<string, string>, extra?: (work: string) => Promise<void>) {
  const bare = join(root, 'sources', `${name}.git`)
  const work = join(root, 'tmp', name)
  await run(root, ['init', '--bare', '--initial-branch=main', bare])
  await run(root, ['init', '--initial-branch=main', work])
  await writeFiles(work, files)
  if (extra) await extra(work)
  await run(work, ['add', '-A'])
  await run(work, ['commit', '-m', `Seed ${name}`])
  await run(work, ['remote', 'add', 'origin', bare])
  await run(work, ['push', 'origin', 'main'])
  return { bare, work }
}

async function seed(root: string, reset: boolean) {
  if (await exists(root)) {
    if (!reset) throw new Error(`${root} exists; pass --reset to recreate it`)
    if (!(await exists(join(root, MARKER)))) throw new Error(`${root} exists but is not a fixture root (no ${MARKER}); refusing to delete it`)
    await rm(root, { recursive: true, force: true })
  }
  await mkdir(join(root, 'sources'), { recursive: true })
  await writeFile(join(root, MARKER), 'Generated by workflow_editor/scripts/seed.ts\n')

  for (const [name, files] of Object.entries(SOURCES)) {
    await source(root, name, files, name === 'devdocs'
      ? async work => { await cp(join(examples, 'workflows'), join(work, 'workflows'), { recursive: true }) }
      : undefined)
  }

  // The project root. Its origin is set first so that relative submodule
  // URLs (../<name>.git) resolve next to it, in sources/.
  const rootBare = join(root, 'sources', 'pj-demo.git')
  const rootWork = join(root, 'tmp', 'pj-demo')
  await run(root, ['init', '--bare', '--initial-branch=main', rootBare])
  await run(root, ['init', '--initial-branch=main', rootWork])
  await run(rootWork, ['remote', 'add', 'origin', rootBare])
  await writeFiles(rootWork, {
    '.gitignore': '.local/\n',
    'README.md': '# pj-demo\n\nSynthetic project for the workflow editor fixture.\n',
  })
  await cp(join(examples, 'project.yaml'), join(rootWork, 'project.yaml'))
  for (const [name, path] of SUBMODULES) await run(rootWork, ['submodule', 'add', `../${name}.git`, path])
  await run(rootWork, ['add', '-A'])
  await run(rootWork, ['commit', '-m', 'Seed pj-demo with submodules'])
  await run(rootWork, ['push', 'origin', 'main'])

  // Two workspaces of the same project. A leaves assets/shared uninitialized
  // and keeps study/agentic-patterns on its branch; everything else is at the
  // recorded commit with a detached HEAD, as `submodule update` leaves it.
  const workspaces = join(root, 'workspaces')
  await mkdir(workspaces, { recursive: true })
  for (const ws of ['a', 'b']) {
    const dir = join(workspaces, ws)
    await run(workspaces, ['clone', rootBare, dir])
    const paths = ws === 'a' ? SUBMODULES.map(s => s[1]).filter(p => p !== 'assets/shared') : []
    await run(dir, ['submodule', 'update', '--init', '--', ...paths])
    await mkdir(join(dir, '.local'), { recursive: true })
    await writeFile(join(dir, '.local', 'README.md'), `Workspace ${ws.toUpperCase()} local files (ignored).\n`)
  }
  await run(join(workspaces, 'a', 'study', 'agentic-patterns'), ['checkout', 'main'])
  await rm(join(root, 'tmp'), { recursive: true, force: true })

  const registry = {
    // Ignored, machine-specific. The editor reads it; nothing tracked does.
    approver: 'fixture-author',
    workspaces: [
      { id: 'a', label: 'Workspace A', host: 'this machine', path: join(workspaces, 'a') },
      { id: 'b', label: 'Workspace B', host: 'this machine', path: join(workspaces, 'b') },
      { id: 'gone', label: 'Removed workspace', host: 'this machine', path: join(workspaces, 'gone') },
    ],
  }
  await writeFile(join(root, 'registry.json'), `${JSON.stringify(registry, null, 2)}\n`)
  return { rootBare, workspaces: await readdir(workspaces) }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = resolve(option('--root') ?? DEFAULT_ROOT)
  const out = await seed(root, flag('--reset')).catch((e: Error) => { console.error(`seed: ${e.message}`); process.exit(1) })
  console.log(`Seeded ${relative(process.cwd(), root) || root}`)
  console.log(`  project origin: ${relative(root, out.rootBare)}`)
  console.log(`  workspaces: ${out.workspaces.join(', ')} (registry.json lists them plus one missing entry)`)
}

export { seed }
