// The context resolver (workflow_editor p13, docs/context.md): one function
// for every consumer — a run's claim, the "next attempt" preview, the
// matrix in the browser, `wfe context show` and an authoring session — so
// they all see the same sources.
//
// Where each scope's sources come from:
//
//   system    default   the common execution contract (the execution host's, by hash at claim)
//                       or, for authoring, the authoring area's entry documents (a reference)
//             local     the blocks of <area>/.local/contexts/system/
//   project   default   project.yaml intent and goals; project.yaml guides
//             local     the blocks of …/projects/<project>/project/
//   workflow  default   the workflow's intent; its execution.guides
//             local     the blocks of …/projects/<project>/workflows/<workflow>/
//   run       input     the run's request and record (named; the brief carries pending input in full)
//
// A run's defaults are read from its own copy of the project and its frozen
// definition; a guide of another project from that project's committed main
// (the commit is recorded); overrides from this area's current settings. A
// guide named by the project and by the workflow is one source with both
// declarations. Each local block is a source of its own (key
// <scope>/block/<id>), instructions before information, by id; a scope
// without blocks contributes nothing; a block or a configured source that
// cannot be read is an error source, never silently left out.
import { createHash } from 'node:crypto'
import { lstat, readFile, realpath } from 'node:fs/promises'
import { CONTEXT_SCHEMA, blockSummary, fingerprintOf, renderBlock, type ContextBundle, type ContextPurpose, type ContextSource, type ScopeTarget } from '../shared/context.ts'
import { guideKey, guideRef, normalizeRepoPath, type Project, type Workflow } from '../shared/model.ts'
import { runKey, type RunRecord } from '../shared/run.ts'
import { runFolder } from '../shared/run.ts'
import type { AccessContext } from './access.ts'
import { ContextStore } from './contextStore.ts'
import { inside } from './files.ts'
import type { Workspace } from './workspace.ts'

const sha256 = (b: string | Buffer) => createHash('sha256').update(b).digest('hex')

export interface ResolveInput {
  purpose: ContextPurpose
  // Where the project's own defaults are read: the run's copy (execution)
  // or the project workspace (authoring).
  ws: Workspace
  // The workflow: a run's frozen definition in force, or the workflow file
  // being authored; null for authoring before a workflow has an identity.
  workflow: Workflow | null
  run?: RunRecord
  // Execution: the common contract the host offers (null: not known yet,
  // as in a preview between attempts — it is decided at claim).
  contract?: { name: string; sha256: string } | null
  host?: string
}

export async function resolveContext(ctx: AccessContext, i: ResolveInput): Promise<ContextBundle> {
  const store = new ContextStore(ctx.area)
  const sources: ContextSource[] = []
  const both: ContextSource['applies'] = ['execution', 'authoring']
  const read = await i.ws.readProject().catch(e => ({ text: null, project: undefined, problem: { kind: 'unreadable', message: (e as Error).message } }))
  const project: Project | undefined = read.project
  const projectId = project?.id || i.ws.reg.project || i.ws.reg.id
  const workflowId = i.run?.workflow ?? i.workflow?.id ?? null

  // ---- system ----
  if (i.purpose === 'execution') {
    sources.push({
      key: 'system/contract', scope: 'system', category: 'default', kind: 'contract', applies: ['execution'],
      title: `common execution contract${i.contract ? ` ${i.contract.name}` : ''}`, origin: { host: i.host ?? 'of this area' }, provenance: ['the execution host'],
      ...(i.contract ? { delivery: 'body' as const, sha256: i.contract.sha256, note: 'composed into the prompt by the execution host before this context' } : { delivery: 'reference' as const, reference: 'the execution host offers it at claim', note: 'decided at claim: the host composes its current contract' }),
    })
  } else {
    sources.push({
      key: 'system/authoring', scope: 'system', category: 'default', kind: 'contract', applies: ['authoring'],
      title: 'authoring entry and file contract', origin: { file: 'authoring/AGENTS.md' }, provenance: ['wfe setup'], delivery: 'reference',
      reference: 'the authoring area\'s AGENTS.md (generated by wfe setup) and docs/contract.md of the installed editor; the common execution contract is for run executors and is not given here',
    })
  }
  sources.push(...await blockSources(store, { scope: 'system' }, both))

  // ---- project ----
  if (project) {
    const body = [project.intent.trim() && `Intent: ${project.intent.trim()}`, project.goals.length ? ['Goals:', ...project.goals.map(g => `- ${g}`)].join('\n') : ''].filter(Boolean).join('\n\n')
    sources.push(body
      ? { key: 'project/intent', scope: 'project', category: 'default', kind: 'intent', applies: both, title: `${project.name || project.id}: intent and goals`, origin: { file: 'project.yaml' }, provenance: ['project.yaml'], delivery: 'body', text: body, sha256: sha256(body) }
      : { key: 'project/intent', scope: 'project', category: 'default', kind: 'intent', applies: both, title: 'intent and goals', origin: { file: 'project.yaml' }, provenance: ['project.yaml'], delivery: 'absent', note: 'project.yaml declares no intent or goals' })
  } else {
    sources.push({ key: 'project/intent', scope: 'project', category: 'default', kind: 'intent', applies: both, title: 'intent and goals', origin: { file: 'project.yaml' }, provenance: ['project.yaml'], delivery: 'error', note: read.problem?.message ?? 'project.yaml cannot be read' })
  }
  // Guides: project.yaml first, then the workflow's own; one source per guide.
  const guides = new Map<string, { scope: 'project' | 'workflow'; provenance: string[]; ref: string }>()
  for (const g of project?.guides ?? []) { const k = guideKey(g); if (!guides.has(k)) guides.set(k, { scope: 'project', provenance: ['project.yaml guides'], ref: g }) }
  for (const g of i.workflow?.execution.guides ?? []) {
    const k = guideKey(g)
    const had = guides.get(k)
    if (had) { if (!had.provenance.includes('workflow execution.guides')) had.provenance.push('workflow execution.guides') }
    else guides.set(k, { scope: 'workflow', provenance: ['workflow execution.guides'], ref: g })
  }
  const guideSources: ContextSource[] = []
  // p18: a standing run (a conversation's conductor) lives as long as its
  // conversation; its copy is as old as the conversation, so its own guides
  // are read from its project's committed main, as another project's are.
  for (const [k, g] of guides) guideSources.push(await guideSource(ctx, i.ws, k, g, i.run?.standing ? projectId : null))
  sources.push(...guideSources.filter(s => s.scope === 'project'))
  sources.push(...await blockSources(store, { scope: 'project', project: projectId }, both))

  // ---- workflow ----
  if (workflowId) {
    const w = i.workflow
    const intent = w?.intent?.trim()
    sources.push(intent
      ? { key: 'workflow/intent', scope: 'workflow', category: 'default', kind: 'intent', applies: both, title: `${w!.name || w!.id}: intent`, origin: { file: i.run ? `definition (frozen with ${runKey(i.run)})` : `devdocs/workflows/${w!.id}.yaml` }, provenance: ['workflow intent'], delivery: 'body', text: intent, sha256: sha256(intent) }
      : { key: 'workflow/intent', scope: 'workflow', category: 'default', kind: 'intent', applies: both, title: 'intent', origin: {}, provenance: ['workflow intent'], delivery: 'absent', note: w ? 'the workflow declares no intent' : 'the workflow definition cannot be read' })
    sources.push(...guideSources.filter(s => s.scope === 'workflow'))
    sources.push(...await blockSources(store, { scope: 'workflow', project: projectId, workflow: workflowId }, both))
  }

  // ---- run input (named; the brief and continuation carry pending input in full) ----
  if (i.run) {
    const r = i.run
    sources.push({ key: 'run/input', scope: 'run', category: 'input', kind: 'input', applies: ['execution'], title: r.input.kind === 'request' ? `request by ${r.input.requester}` : `the person's request (${r.input.author})`, origin: { file: `${runFolder(r)}/${r.input.file}` }, provenance: ['run.create'], delivery: 'reference', reference: `${runFolder(r)}/${r.input.file}`, ...(r.input.sha256 ? { sha256: r.input.sha256 } : {}) })
    sources.push({ key: 'run/record', scope: 'run', category: 'input', kind: 'input', applies: ['execution'], title: 'answers, instructions and delegation facts', origin: { file: `${runFolder(r)}/run.json` }, provenance: ['run record'], delivery: 'reference', reference: `wfe run state ${runKey(r)} (pending input is given in full in the attempt's brief)` })
  }
  const bundle: ContextBundle = { schema: CONTEXT_SCHEMA, purpose: i.purpose, project: projectId, workflow: workflowId, run: i.run?.run ?? null, resolved: new Date().toISOString(), sources, fingerprint: '' }
  bundle.fingerprint = fingerprintOf(bundle)
  return bundle
}

// The blocks of one scope, each a source: its rendered section is what it
// delivers, and that section's hash is its sha256.
async function blockSources(store: ContextStore, t: ScopeTarget, applies: ContextSource['applies']): Promise<ContextSource[]> {
  const out: ContextSource[] = []
  for (const s of await store.blocks(t)) {
    const base = { key: `${t.scope}/block/${s.id}`, scope: t.scope, category: 'override' as const, kind: 'block' as const, applies, origin: { file: s.file }, provenance: ['local context'] }
    if (s.problem) { out.push({ ...base, title: s.id, delivery: 'error', note: s.problem }); continue }
    if (!s.block) continue // removed: only its history remains
    const text = renderBlock(t, s.block)
    out.push({ ...base, title: s.block.title, delivery: 'body', text, sha256: s.sha256!, block: blockSummary(s.block, s.revision), ...(s.external ? { note: 'edited outside WFE since its last recorded revision' } : {}) })
  }
  return out
}

async function guideSource(ctx: AccessContext, ws: Workspace, key: string, g: { scope: 'project' | 'workflow'; provenance: string[]; ref: string }, fromMain: string | null = null): Promise<ContextSource> {
  const ref = guideRef(g.ref)
  const base = { key: `guide/${key}`, scope: g.scope, category: 'default' as const, kind: 'guide' as const, applies: ['execution', 'authoring'] as ContextSource['applies'], title: `guide ${key}`, provenance: g.provenance }
  if (ref.project) {
    // A guide of another managed project (project_migration p4): its committed main.
    if (!ref.path || ref.path === '.') return { ...base, origin: {}, delivery: 'error', note: `"${g.ref}" is not <project>:<path>` }
    try {
      const { committedText } = await import('./access.ts')
      const r = await committedText({ ...ctx, refresh: true }, ref.project, ref.path)
      return { ...base, origin: { project: ref.project, file: ref.path, commit: r.commit }, delivery: 'body', text: r.text, sha256: r.sha256 }
    } catch (e) {
      return { ...base, origin: { project: ref.project, file: ref.path }, delivery: 'error', note: `cannot be read from project ${ref.project}: ${(e as Error).message}` }
    }
  }
  const path = normalizeRepoPath(g.ref)
  if (!path || path === '.') return { ...base, origin: {}, delivery: 'error', note: `"${g.ref}" is not a project-relative path` }
  let unread = ''
  if (fromMain) {
    try {
      const { committedText } = await import('./access.ts')
      const r = await committedText({ ...ctx, refresh: true }, fromMain, path)
      return { ...base, origin: { project: fromMain, file: path, commit: r.commit }, delivery: 'body', text: r.text, sha256: r.sha256, note: 'a standing run reads its own guides from its project\'s committed main' }
    } catch (e) { unread = `its project's committed main could not be read (${(e as Error).message}); read from this run's copy` }
  }
  try {
    const abs = await inside(ws.root, path)
    const l = await lstat(abs)
    if (!l.isFile() || l.isSymbolicLink() || !(await realpath(abs)).startsWith(await realpath(ws.root))) return { ...base, origin: { file: path }, delivery: 'error', note: `${path} is not a regular file of the project` }
    const bytes = await readFile(abs)
    return { ...base, origin: { file: path }, delivery: 'body', text: bytes.toString('utf8'), sha256: sha256(bytes), ...(unread ? { note: unread } : {}) }
  } catch (e) {
    return { ...base, origin: { file: path }, delivery: 'error', note: `${path} cannot be read: ${(e as NodeJS.ErrnoException).code === 'ENOENT' ? 'no such file' : (e as Error).message}` }
  }
}

// The errors that keep an attempt from being prepared: a configured source
// that cannot be read (the job is refused with the reason, as a missing
// guide always was).
export const contextErrors = (b: ContextBundle) => b.sources.filter(s => s.delivery === 'error').map(s => `${s.key}: ${s.note}`)
